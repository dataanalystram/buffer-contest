"""Build studio/static/brand-logos-data.js: the marks for Settings > Integrations, the AI engine cards and the landing
page's "Works with" strip.

    python scripts/build_brand_logos.py <simple-icons package dir>

Source (see NOTICE and docs/UI_CREDITS.md): simple-icons 16.36.0 (CC0 1.0 for the icon set; every mark stays its owner's
trademark and is used only to say HuhQueue works with that service). LinkedIn, OpenAI and Groq are not in simple-icons:
LinkedIn keeps its "in" monogram (net-logos.js), OpenAI comes from ai-logos.js (openai.com/brand), Groq is a monogram."""
import json
import re
import sys
from pathlib import Path

SI = {  # id -> (simple-icons slug, label)
    "buffer": ("buffer", "Buffer"), "instagram": ("instagram", "Instagram"), "youtube": ("youtube", "YouTube"),
    "tiktok": ("tiktok", "TikTok"), "facebook": ("facebook", "Facebook"), "x": ("x", "X"), "threads": ("threads", "Threads"),
    "bluesky": ("bluesky", "Bluesky"), "producthunt": ("producthunt", "Product Hunt"), "huggingface": ("huggingface", "Hugging Face"),
    "nvidia": ("nvidia", "NVIDIA"), "gemini": ("googlegemini", "Google Gemini"), "claude": ("claude", "Claude"),
    "anthropic": ("anthropic", "Anthropic"), "mcp": ("modelcontextprotocol", "Model Context Protocol"),
    "github": ("github", "GitHub"), "openrouter": ("openrouter", "OpenRouter"), "googlecloud": ("googlecloud", "Google Cloud"),
}


def inner(svg: str) -> tuple[str, str]:
    vb = re.search(r'viewBox="([^"]+)"', svg).group(1)
    body = re.sub(r"^.*?<svg[^>]*>|</svg>\s*$", "", svg, flags=re.S)
    body = re.sub(r"<title>.*?</title>", "", body)
    body = re.sub(r'\sfill="(white|black|#[0-9a-fA-F]{3,6})"', "", body)
    return vb, re.sub(r"\s+", " ", body).strip()


def main(si_dir):
    data = json.loads((Path(si_dir) / "data" / "simple-icons.json").read_text())
    hexes = {d.get("slug") or re.sub(r"[^a-z0-9]", "", d["title"].lower()): d["hex"] for d in data}
    out = {}
    for k, (slug, label) in SI.items():
        vb, body = inner((Path(si_dir) / "icons" / f"{slug}.svg").read_text())
        out[k] = {"label": label, "hex": "#" + hexes.get(slug, "111111"), "vb": vb, "svg": body, "src": f"simple-icons/{slug}"}
    js = Path(__file__).resolve().parent.parent / "studio" / "static" / "brand-logos-data.js"
    js.write_text("// GENERATED by scripts/build_brand_logos.py from simple-icons 16.36.0 (CC0). Marks are trademarks of their owners; see NOTICE.\n"
                  "window.HQ_BRAND_DATA = " + json.dumps(out, separators=(",", ":")) + ";\n")
    print(js, len(out), "marks")


if __name__ == "__main__":
    main(sys.argv[1])
