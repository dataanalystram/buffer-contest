"""Build studio/static/net-logos.js: the social network marks HuhQueue shows next to every post and channel.

    python scripts/build_net_logos.py <simple-icons package dir>

Source (see NOTICE and docs/UI_CREDITS.md): simple-icons 16.36.0 (CC0 for the icon set; every mark stays its owner's
trademark). LinkedIn is not in simple-icons (removed at LinkedIn's request), so it keeps a plain "in" monogram on
LinkedIn blue; Google Business uses the Google "G". Anything unknown falls back to a two-letter monogram in net-logos.js."""
import json
import re
import sys
from pathlib import Path

# Buffer service id -> (simple-icons slug, label)
SI = {
    "twitter": ("x", "X"), "instagram": ("instagram", "Instagram"), "facebook": ("facebook", "Facebook"),
    "youtube": ("youtube", "YouTube"), "threads": ("threads", "Threads"), "tiktok": ("tiktok", "TikTok"),
    "bluesky": ("bluesky", "Bluesky"), "mastodon": ("mastodon", "Mastodon"), "pinterest": ("pinterest", "Pinterest"),
    "googlebusiness": ("google", "Google Business"),
}


def inner(svg: str) -> tuple[str, str]:
    vb = re.search(r'viewBox="([^"]+)"', svg).group(1)
    body = re.sub(r"^.*?<svg[^>]*>|</svg>\s*$", "", svg, flags=re.S)
    body = re.sub(r"<title>.*?</title>", "", body)
    body = re.sub(r'\sfill="(white|black|#[0-9a-fA-F]{3,6})"', "", body)
    return vb, re.sub(r"\s+", " ", body).strip()


def main(si_dir):
    data = json.loads((Path(si_dir) / "data" / "simple-icons.json").read_text())
    hexes = {d.get("slug") or re.sub(r"[^a-z0-9]", "", d["title"].lower()): d["hex"] for d in data}
    out = {}
    for k, (slug, label) in SI.items():
        vb, body = inner((Path(si_dir) / "icons" / f"{slug}.svg").read_text())
        out[k] = {"label": label, "hex": "#" + hexes.get(slug, "111111"), "vb": vb, "svg": body, "src": f"simple-icons/{slug}"}
    js = Path(__file__).resolve().parent.parent / "studio" / "static" / "net-logos-data.js"
    js.write_text("// GENERATED by scripts/build_net_logos.py from simple-icons 16.36.0 (CC0). Marks are trademarks of their owners; see NOTICE.\n"
                  "window.HQ_NET_DATA = " + json.dumps(out, separators=(",", ":")) + ";\n")
    print(js, len(out), "marks")


if __name__ == "__main__":
    main(sys.argv[1])
