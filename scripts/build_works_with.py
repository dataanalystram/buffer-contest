"""Write the landing page's "Works with" strip (studio/static/landing.html, between the WORKS-WITH markers) from
studio/static/brand-logos-data.js, so the page needs no script for it. Marks: simple-icons 16.36.0 (CC0; trademarks of
their owners, used only to say HuhQueue works with them). LinkedIn is not in simple-icons, so it is an "in" monogram.

    python scripts/build_works_with.py
"""
import html
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent / "studio" / "static"
ITEMS = ["buffer", "instagram", "youtube", "tiktok", "linkedin", "facebook", "x", "threads", "bluesky", "producthunt",
         "huggingface", "nvidia", "gemini", "claude", "mcp", "github"]
LABEL = {"mcp": "MCP", "gemini": "Gemini"}


def main():
    t = (ROOT / "brand-logos-data.js").read_text()
    data = json.loads(t[t.index("{"):t.rindex("}") + 1])
    lis = []
    for k in ITEMS:
        if k == "linkedin":
            svg = ('<svg viewBox="0 0 24 24" role="img" aria-label="LinkedIn" focusable="false"><title>LinkedIn</title>'
                   '<rect x="1.5" y="1.5" width="21" height="21" rx="4" fill="currentColor"/>'
                   '<text x="12" y="17" text-anchor="middle" font-size="12" font-weight="800" font-family="Arial,sans-serif" fill="var(--paper)">in</text></svg>')
            hexv, name = "#0A66C2", "LinkedIn"
        else:
            d = data[k]
            name = LABEL.get(k, d["label"])
            svg = (f'<svg viewBox="{d["vb"]}" role="img" aria-label="{html.escape(d["label"])}" focusable="false">'
                   f'<title>{html.escape(d["label"])}</title>{d["svg"]}</svg>')
            hexv = d["hex"]
        lis.append(f'<li style="--brand:{hexv}" data-testid="works-with-{k}">{svg}<span>{html.escape(name)}</span></li>')
    block = ('<!-- WORKS-WITH:start (generated by scripts/build_works_with.py) -->\n'
             '  <section class="works wrap" id="works-with" aria-labelledby="wwH" data-testid="works-with">\n'
             '    <h2 class="works-h" id="wwH">Works with</h2>\n'
             '    <ul class="works-list" aria-label="Services HuhQueue works with">' + "".join(lis) + '</ul>\n'
             '    <p class="works-note">Logos are trademarks of their owners; HuhQueue is independent and not endorsed by them. Icons: simple-icons (CC0).</p>\n'
             '  </section>\n  <!-- WORKS-WITH:end -->')
    p = ROOT / "landing.html"
    s = p.read_text()
    if "<!-- WORKS-WITH:start" in s:
        s = re.sub(r"<!-- WORKS-WITH:start.*?<!-- WORKS-WITH:end -->", lambda m: block, s, flags=re.S)
    else:
        s = s.replace('  <section class="made-wall" id="made"', "  " + block + '\n\n  <section class="made-wall" id="made"', 1)
    p.write_text(s)
    print("works-with:", len(lis), "marks")


if __name__ == "__main__":
    main()
