"""Build studio/static/ai-logos.js: official marks for the AI apps and models HuhQueue names in the UI.

    python scripts/build_ai_logos.py <simple-icons package dir> <openai symbol svg> <xAI_Grok_Assets dir>

Sources (see NOTICE and docs/UI_CREDITS.md): simple-icons 16.36.0 (CC0 for the icon set; every mark stays its owner's
trademark), OpenAI's Blossom from openai.com/brand (file as mirrored on Wikimedia Commons, "OpenAI logo 2025 (symbol)"),
and xAI/Grok marks from xAI's own press kit (data.x.ai/logos/xAI_Grok_Assets.zip). Anything else gets a monogram."""
import json
import re
import sys
from pathlib import Path

SI = {  # id -> (simple-icons slug, label)
    "claude": ("claude", "Claude"), "claude-code": ("claudecode", "Claude Code"), "anthropic": ("anthropic", "Anthropic"),
    "cursor": ("cursor", "Cursor"), "gemini": ("googlegemini", "Gemini"), "mistral": ("mistralai", "Mistral"),
    "meta": ("meta", "Meta"), "perplexity": ("perplexity", "Perplexity"), "openrouter": ("openrouter", "OpenRouter"),
    "deepseek": ("deepseek", "DeepSeek"), "qwen": ("qwen", "Qwen"), "huggingface": ("huggingface", "Hugging Face"),
    "ollama": ("ollama", "Ollama"), "copilot": ("githubcopilot", "GitHub Copilot"),
}


def inner(svg: str) -> tuple[str, str]:
    vb = re.search(r'viewBox="([^"]+)"', svg).group(1)
    body = re.sub(r"^.*?<svg[^>]*>|</svg>\s*$", "", svg, flags=re.S)
    body = re.sub(r"<title>.*?</title>", "", body)
    body = re.sub(r'\sfill="(white|black|#[0-9a-fA-F]{3,6})"', "", body)
    return vb, re.sub(r"\s+", " ", body).strip()


def main(si_dir, oai, xai_dir):
    data = json.loads((Path(si_dir) / "data" / "simple-icons.json").read_text())
    hexes = {d.get("slug") or re.sub(r"[^a-z0-9]", "", d["title"].lower()): d["hex"] for d in data}
    out = {}
    for k, (slug, label) in SI.items():
        vb, body = inner((Path(si_dir) / "icons" / f"{slug}.svg").read_text())
        out[k] = {"label": label, "hex": "#" + hexes.get(slug, "111111"), "vb": vb, "svg": body, "src": f"simple-icons/{slug}"}
    vb, body = inner(Path(oai).read_text())
    out["openai"] = {"label": "OpenAI", "hex": "#000000", "vb": vb, "svg": body, "src": "openai.com/brand (Blossom)"}
    vb, body = inner((Path(xai_dir) / "Grok_Logomark_Light.svg").read_text())
    out["grok"] = {"label": "Grok", "hex": "#000000", "vb": vb, "svg": body, "src": "xAI press kit (Grok logomark)"}
    vb, body = inner((Path(xai_dir) / "xAI_Logomark_Light.svg").read_text())
    out["xai"] = {"label": "xAI", "hex": "#000000", "vb": vb, "svg": body, "src": "xAI press kit (xAI logomark)"}
    js = Path(__file__).resolve().parent.parent / "studio" / "static" / "ai-logos.js"
    js.write_text("// GENERATED by scripts/build_ai_logos.py. Marks are trademarks of their owners; sources in NOTICE.\n"
                  "window.HQ_LOGO_DATA = " + json.dumps(out, separators=(",", ":")) + ";\n")
    print(js, len(out), "marks")


if __name__ == "__main__":
    main(*sys.argv[1:4])
