def drop_extra_hashtags(text: str, keep: int = 30) -> str:
    seen = 0

    def sub(m):
        nonlocal seen
        seen += 1
        return m.group(0) if seen <= keep else ""
    out = HASHTAG_RE.sub(sub, text)
    return re.sub(r"[ \t]{2,}", " ", out).strip()


def fit_text(service: str, text: str, limit: int) -> str:
    """Trim at a sentence/word boundary under the network's count; keep a trailing URL."""
    if count_text(service, text) <= limit:
        return text
    url = ""
    m = re.search(r"\s(https?://\S+)\s*$", text)
    if m:
        url, text = m.group(1), text[: m.start()].rstrip()
    suffix = ("…\n\n" + url) if url else "…"
    while text and count_text(service, text + suffix) > limit:
        cut = max(text.rfind(". ", 0, len(text) - 1), text.rfind(" ", 0, len(text) - 1))
        text = text[:cut].rstrip(" ,;:-") if cut > 0 else text[:-1]
    return (text + suffix).strip()


def thread_text(service: str, text: str, limit: int) -> str:
    """Split into thread parts under the limit, at sentence then word boundaries, numbered n/N."""
    words = re.split(r"(?<=[.!?])\s+|\s+", " ".join(text.replace("\n---\n", "\n").split()))
    budget = limit - 6  # room for " 10/12"
    parts, cur = [], ""
    for w in words:
        if not w:
            continue
        cand = (cur + " " + w).strip()
        if count_text(service, cand) <= budget:
            cur = cand
        else:
            if cur:
                parts.append(cur)
            cur = w if count_text(service, w) <= budget else fit_text(service, w, budget)
    if cur:
        parts.append(cur)
    if len(parts) > 1:
        parts = [f"{p} {i}/{len(parts)}" for i, p in enumerate(parts, 1)]
    return "\n---\n".join(parts)


def fit_image(service: str, data: bytes) -> tuple[bytes, str]:
    """Make an image pass the network's rules: crop to the allowed aspect range, cap the size/resolution, convert to
    JPEG where the network wants it, and recompress under the byte limit. Returns (bytes, extension)."""
    from PIL import Image, ImageOps
    im = Image.open(io.BytesIO(data))
    im = ImageOps.exif_transpose(im)
    w, h = im.size
    lo, hi = {"instagram": (0.8, 1.91), "threads": (0.1, 10.0)}.get(service, (0.0, 1e9))
    r = w / h
    if r < lo:  # too tall: crop height, centred
        nh = int(round(w / lo))
        top = (h - nh) // 2
        im = im.crop((0, top, w, top + nh))
    elif r > hi:  # too wide: crop width, centred
        nw = int(round(h * hi))
        left = (w - nw) // 2
        im = im.crop((left, 0, left + nw, h))
    max_w = {"instagram": 1440, "threads": 1440}.get(service)
    if max_w and im.width > max_w:
        im = im.resize((max_w, int(im.height * max_w / im.width)), Image.LANCZOS)
    if service == "tiktok" and min(im.size) > 1080:
        s = 1080 / min(im.size)
        im = im.resize((int(im.width * s), int(im.height * s)), Image.LANCZOS)
    if service == "linkedin" and im.width * im.height >= 36_152_320:
        s = (36_000_000 / (im.width * im.height)) ** 0.5
        im = im.resize((int(im.width * s), int(im.height * s)), Image.LANCZOS)
    cap = {"instagram": 8 * MB, "threads": 8 * MB, "twitter": 5 * MB, "bluesky": 1_000_000, "tiktok": 20 * MB}.get(service, 8 * MB)
    if im.mode not in ("RGB", "L"):
        bg = Image.new("RGB", im.size, (255, 255, 255))
        bg.paste(im, mask=im.convert("RGBA").split()[-1])
        im = bg
    im = im.convert("RGB")
    q = 92
    while True:
        buf = io.BytesIO()
        im.save(buf, "JPEG", quality=q, optimize=True)
        out = buf.getvalue()
        if len(out) <= cap or q <= 40:
            if len(out) > cap:  # still too big: scale down
                im = im.resize((int(im.width * 0.8), int(im.height * 0.8)), Image.LANCZOS)
                q = 85
                continue
            return out, "jpg"
        q -= 8


def apply_text_fixes(channel: dict, text: str, options: dict, fix_ids: list[str], has_video: bool = False) -> tuple[str, dict, list[str]]:
    svc = channel.get("service", "")
    limit, _, _ = text_limit(channel, has_video, options)
    applied = []
    options = dict(options or {})
    if "drop_hashtags" in fix_ids:
        text = drop_extra_hashtags(text, 30)
        applied.append("drop_hashtags")
    if "thread" in fix_ids and svc in THREAD_SERVICES:
        parts = split_thread(svc, text)
        out = []
        for p in parts:
            out.append(thread_text(svc, p, limit) if count_text(svc, p) > limit else p)
        text = "\n---\n".join(out)
        applied.append("thread")
    elif "trim" in fix_ids:
        parts = split_thread(svc, text)
        text = "\n---\n".join(fit_text(svc, p, limit) for p in parts)
        applied.append("trim")
    if "youtube_title" in fix_ids:
        options["title"] = fit_text("youtube", (options.get("title") or text.split("\n")[0]).strip(), 100)
        applied.append("youtube_title")
    if "youtube_category" in fix_ids:
        options["category_id"] = "22"
        applied.append("youtube_category")
    return text, options, applied


