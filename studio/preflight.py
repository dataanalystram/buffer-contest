# ------------------------------------------------------------------ counting
URL_RE = re.compile(r"https?://[^\s<>\"]+")
HASHTAG_RE = re.compile(r"(?<![\w&])#(\w+)")
MENTION_RE = re.compile(r"(?<![\w.@])@([A-Za-z0-9_.]+)")
MASTO_MENTION_RE = re.compile(r"(@[A-Za-z0-9_]+)@[A-Za-z0-9.-]+\.[A-Za-z]{2,}")
# twitter-text v3: code points in these ranges weigh 1, everything else 2; an emoji sequence weighs 2
X_LIGHT = ((0, 4351), (8192, 8205), (8208, 8223), (8242, 8247))


def utf16(s: str) -> int:
    return len(s.encode("utf-16-le")) // 2


def _ext(cp: int) -> bool:
    """Code points that extend the previous grapheme (combining marks, ZWJ, variation selectors, skin tones, tags)."""
    return (unicodedata.category(chr(cp)).startswith("M") or cp == 0x200D or 0xFE00 <= cp <= 0xFE0F
            or 0x1F3FB <= cp <= 0x1F3FF or 0xE0020 <= cp <= 0xE007F or 0xE0100 <= cp <= 0xE01EF)


def graphemes(s: str) -> list[str]:
    """Extended grapheme clusters, close enough for counting (no third-party dependency)."""
    out: list[str] = []
    prev = None
    for ch in s:
        cp = ord(ch)
        ri = 0x1F1E6 <= cp <= 0x1F1FF
        if out and (_ext(cp) or prev == 0x200D or (prev == 0x0D and cp == 0x0A)
                    or (ri and len(out[-1]) == 1 and 0x1F1E6 <= ord(out[-1]) <= 0x1F1FF)):
            out[-1] += ch
        else:
            out.append(ch)
        prev = cp
    return out


def _is_emoji(g: str) -> bool:
    for ch in g:
        cp = ord(ch)
        if (0x1F000 <= cp <= 0x1FAFF or 0x2600 <= cp <= 0x27BF or 0x2300 <= cp <= 0x23FF or 0x2B00 <= cp <= 0x2BFF
                or cp == 0x200D or cp == 0xFE0F):
            return True
    return False


def x_weighted(text: str) -> int:
    text = unicodedata.normalize("NFC", text)
    n, last = 0, 0
    for m in URL_RE.finditer(text):
        n += _x_plain(text[last:m.start()]) + 23
        last = m.end()
    return n + _x_plain(text[last:])


def _x_plain(s: str) -> int:
    n = 0
    for g in graphemes(s):
        if len(g) > 1 and _is_emoji(g) or (len(g) == 1 and _is_emoji(g) and ord(g) > 0xFFFF):
            n += 2
            continue
        for ch in g:
            cp = ord(ch)
            n += 1 if any(a <= cp <= b for a, b in X_LIGHT) else 2
    return n


def _bsky_url(u: str) -> str:
    p = urlparse(u)
    rest = u.split(p.netloc, 1)[-1] if p.netloc else ""
    return (p.hostname or "") + rest[:16]


def count_text(service: str, text: str) -> int:
    """Buffer's character count for one post (or one thread part) on a network."""
    text = text.replace("\r\n", "\n")
    if service == "twitter":
        return x_weighted(text)
    if service == "bluesky":
        return len(graphemes(URL_RE.sub(lambda m: _bsky_url(m.group()), text)))
    if service == "mastodon":
        return utf16(MASTO_MENTION_RE.sub(r"\1", URL_RE.sub("x" * 23, text)))
    if service == "linkedin":
        return utf16(URL_RE.sub("x" * 24, text))
    if service == "instagram":
        return utf16(text) + text.count("\n")
    return utf16(text)


def text_limit(channel: dict, has_video: bool = False, options: dict | None = None) -> tuple[int, str, list[str]]:
    """(limit, rule id, notes) for a channel's post text."""
    svc, options, notes = channel.get("service", ""), options or {}, []
    if svc == "tiktok" and has_video:
        return 2200, "text.tiktok.video", notes
    if svc == "twitter" and options.get("x_long_posts"):
        return 25000, "text.twitter.paid", notes
    if svc == "mastodon":
        mx = (channel.get("metadata") or {}).get("maxCharacters") or channel.get("maxCharacters")
        if mx:
            return min(int(mx), 20000), "text.mastodon.cap" if int(mx) > 20000 else "text.mastodon", notes
        notes.append("Mastodon server limit not shared by Buffer for this channel; using the default 500.")
        return 500, "text.mastodon", notes
    r = RULE.get(f"text.{svc}")
    return (r["limit"], r["id"], notes) if r else (2000, "", notes)


def split_thread(service: str, text: str) -> list[str]:
    if service not in THREAD_SERVICES:
        return [text]
    return [p.strip() for p in re.split(r"\n[ \t]*---[ \t]*\n", text) if p.strip()] or [text]


# ------------------------------------------------------------------ media probing
VIDEO_EXT = (".mp4", ".mov", ".m4v", ".webm")
IMAGE_EXT = (".jpg", ".jpeg", ".png", ".gif", ".webp")
_CACHE: dict[str, tuple[float, dict]] = {}
CACHE_TTL = 3600


def kind_of(url: str, probe: dict | None = None) -> str:
    if probe and probe.get("kind") in ("image", "video"):
        return probe["kind"]
    path = urlparse(url).path.lower()
    return "video" if path.endswith(VIDEO_EXT) else "image"


def probe_bytes(data: bytes, hint: str = "") -> dict:
    """Facts about one media file: kind, format, size, width/height, and for video duration/fps/bitrates/codec."""
    out: dict = {"bytes": len(data)}
    try:
        from PIL import Image
        with Image.open(io.BytesIO(data)) as im:
            out.update(kind="image", format=(im.format or "").upper(), width=im.width, height=im.height,
                       animated=bool(getattr(im, "is_animated", False)))
            return out
    except Exception:
        pass
    if data[4:8] == b"ftyp" or data[:4] == b"\x1aE\xdf\xa3" or hint.endswith(VIDEO_EXT):
        out["kind"] = "video"
        out.update(ffprobe_bytes(data))
        return out
    out["kind"] = "unknown"
    return out


def ffprobe_bytes(data: bytes) -> dict:
    if not shutil.which("ffprobe"):
        return {"probed": False, "why": "ffprobe is not installed on this server"}
    with tempfile.NamedTemporaryFile(suffix=".bin") as f:
        f.write(data)
        f.flush()
        try:
            r = subprocess.run(["ffprobe", "-v", "error", "-print_format", "json", "-show_format", "-show_streams", f.name],
                               capture_output=True, timeout=30, check=False)
            j = json.loads(r.stdout or b"{}")
        except Exception as e:  # noqa: BLE001 - a broken file is a finding, not a crash
            return {"probed": False, "why": f"ffprobe failed: {e}"}
    return parse_ffprobe(j)


def parse_ffprobe(j: dict) -> dict:
    v = next((s for s in j.get("streams", []) if s.get("codec_type") == "video"), None)
    a = next((s for s in j.get("streams", []) if s.get("codec_type") == "audio"), None)
    fmt = j.get("format") or {}
    if not v:
        return {"probed": False, "why": "no video stream found"}

    def num(x):
        try:
            return float(x)
        except (TypeError, ValueError):
            return None

    fps = None
    rate = v.get("avg_frame_rate") or v.get("r_frame_rate") or ""
    if "/" in rate:
        n, d = rate.split("/", 1)
        fps = round(num(n) / num(d), 2) if num(d) else None
    return {"probed": True, "codec": v.get("codec_name"), "width": v.get("width"), "height": v.get("height"), "fps": fps,
            "duration": num(fmt.get("duration")) or num(v.get("duration")),
            "video_kbps": round((num(v.get("bit_rate")) or num(fmt.get("bit_rate")) or 0) / 1000) or None,
            "audio_kbps": round((num(a.get("bit_rate")) or 0) / 1000) or None if a else None,
            "container": fmt.get("format_name")}


def probe_url(url: str, loader: Callable[[str], bytes | None] | None) -> dict:
    hit = _CACHE.get(url)
    if hit and time.time() - hit[0] < CACHE_TTL:
        return hit[1]
    data = None
    if loader:
        try:
            data = loader(url)
        except Exception:  # noqa: BLE001 - unreachable media is reported, never raised
            data = None
    res = probe_bytes(data, urlparse(url).path.lower()) if data else {"kind": "unknown", "unreachable": True}
    if len(_CACHE) > 256:
        _CACHE.clear()
    _CACHE[url] = (time.time(), res)
    return res


# ------------------------------------------------------------------ the check
def _f(level: str, rule: str, message: str, fix: str | None = None) -> dict:
    r = RULE.get(rule) or {}
    return {"level": level, "rule": rule, "message": message, "source": r.get("source", ""), **({"fix": fix} if fix else {})}


def _ratio_label(w: int, h: int) -> str:
    return f"{w}×{h}"


def check(channel: dict, text: str, media_urls: list[str] | None = None, mode: str = "queue", options: dict | None = None,
          loader: Callable[[str], bytes | None] | None = None, probe_media: bool = True, creating: bool = True,
          media_kinds: list[str] | None = None) -> dict:
    """Preflight one post for one channel. Pure apart from media probing (loader fetches bytes; None skips probing)."""
    svc = channel.get("service", "")
    net = NETWORK.get(svc, svc)
    options = dict(options or {})
    media_urls = [u for u in (media_urls or []) if u]
    draft = mode == "draft"
    findings: list[dict] = []
    fixes: dict[str, str] = {}
    probes = [probe_url(u, loader) if (probe_media and loader) else {"kind": "unknown", "skipped": True} for u in media_urls]
    kinds = [kind_of(u, p) for u, p in zip(media_urls, probes)]
    if media_kinds and len(media_kinds) == len(kinds):
        kinds = [k if p.get("kind") in ("image", "video") else h for k, p, h in zip(kinds, probes, media_kinds)]
    has_video = "video" in kinds

    # ---- text
    text = (text or "").replace("\r\n", "\n")
    limit, rule_id, notes = text_limit(channel, has_video, options)
    for n in notes:
        findings.append(_f("info", rule_id, n))
    parts = split_thread(svc, text)
    counts = [count_text(svc, p) for p in parts]
    longest = max(counts) if counts else 0
    if not text.strip():
        findings.append(_f("error", rule_id, "Post text is empty."))
    for i, (p, n) in enumerate(zip(parts, counts), 1):
        if n > limit:
            where = f"Thread post {i}: " if len(parts) > 1 else ""
            extra = []
            if utf16(p) > len(p):
                extra.append("emoji and styled letters count 2")
            if svc == "instagram" and "\n" in p:
                extra.append("line breaks count 2")
            if svc == "linkedin" and URL_RE.search(p):
                extra.append("links count 24")
            hint = f" ({'; '.join(extra)})" if extra else ""
            if svc in THREAD_SERVICES:
                fixes["thread"] = f"Split into a thread of posts under {limit:,}"
                fixes.setdefault("trim", f"Trim to {limit:,} characters")
                fix = "thread"
            else:
                fixes["trim"] = f"Trim to {limit:,} characters"
                fix = "trim"
            findings.append(_f("error", rule_id, f"{where}{n:,}/{limit:,} characters: too long for {net}{hint}.", fix))
    if svc == "tiktok" and has_video and longest > 2200:
        pass  # covered above by the video limit

    # ---- fields (required on create; on edit Buffer keeps the existing value when omitted)
    if svc == "youtube" and creating:
        title = (options.get("title") or text.split("\n")[0]).strip()
        lvl = "info" if draft else "error"
        if not title:
            findings.append(_f(lvl, "field.youtube.title", "YouTube needs a title (the first line of the text is used)."))
        elif utf16(title) > 100:
            fixes["youtube_title"] = "Shorten the title to 100"
            findings.append(_f("error", "field.youtube.title", f"YouTube title is {utf16(title)}/100 characters.", "youtube_title"))
        cat = str(options.get("category_id") or "")
        if not cat:
            fixes["youtube_category"] = "Use category People & Blogs (22)"
            findings.append(_f(lvl, "field.youtube.category", "YouTube needs a category (categoryId) before Buffer will create it.",
                               "youtube_category"))
        elif cat not in YT_CATEGORIES:
            findings.append(_f("error", "field.youtube.category", f"YouTube category {cat} isn't one Buffer accepts."))
    if svc == "pinterest" and creating:
        if not options.get("board_id"):
            findings.append(_f("info" if draft else "error", "field.pinterest.board",
                               "Pinterest needs a board (boardServiceId) before Buffer will create the Pin."))
        if options.get("title") and utf16(options["title"]) > 100:
            findings.append(_f("error", "field.pinterest.title", f"Pin title is {utf16(options['title'])}/100 characters."))
    if svc == "threads" and options.get("topic"):
        t = options["topic"]
        if utf16(t) > 50 or "&" in t or "." in t:
            findings.append(_f("error", "field.threads.topic", "Threads topic must be 50 characters or fewer, without '&' or '.'."))

    # ---- hashtags and mentions
    if svc == "instagram":
        tags = HASHTAG_RE.findall(text)
        if len(tags) > 30:
            fixes["drop_hashtags"] = "Keep the first 30 hashtags"
            findings.append(_f("error", "tags.instagram.hashtags", f"{len(tags)} hashtags: Instagram allows 30.", "drop_hashtags"))
        ments = MENTION_RE.findall(text)
        if len(ments) > 20:
            findings.append(_f("error", "tags.instagram.mentions", f"{len(ments)} @ mentions: Instagram allows 20."))

    # ---- media URLs
    for i, u in enumerate(media_urls):
        host = (urlparse(u).hostname or "").lower()
        q = {k.lower() for k in parse_qs(urlparse(u).query)}
        if host in ("drive.google.com", "docs.google.com") or (host.endswith("dropbox.com") and "raw" not in q and "dl" not in q):
            findings.append(_f("error", "url.public", f"Media {i + 1} is a share page, not the file. Buffer can't fetch it."))
        elif q & {"x-amz-signature", "x-amz-expires", "signature", "expires", "sig", "se", "token"}:
            findings.append(_f("warning", "url.public", f"Media {i + 1} looks like a signed link that may expire before the post goes out."))

    # ---- media count and mix
    n_img, n_vid = kinds.count("image"), kinds.count("video")
    keep = None
    if svc == "twitter" and media_urls:
        gifs = sum(1 for p in probes if p.get("format") == "GIF")
        if n_vid and len(media_urls) > 1 or gifs and len(media_urls) > 1:
            findings.append(_f("error", "count.twitter", "X takes up to 4 photos, or one GIF, or one video, not a mix."))
        elif n_img > 4:
            keep = 4
    if svc == "bluesky" and n_img > 4:
        keep = 4
    if svc == "instagram" and len(media_urls) > 20:
        keep = 20
    if svc == "threads" and len(media_urls) > 20:
        keep = 20
    if svc == "linkedin" and len(media_urls) > 1:
        if n_vid:
            findings.append(_f("error", "count.linkedin", "LinkedIn multi-image posts take images only; post the video on its own."))
        elif n_img > 20:
            keep = 20
    if keep:
        fixes[f"keep_first:{keep}"] = f"Keep the first {keep} items"
        rid = f"count.{svc}"
        findings.append(_f("error", rid, f"{len(media_urls)} items: {net} allows {keep} in one post.", f"keep_first:{keep}"))

    # ---- per-item media specs
    chips_media = []
    for i, (u, p) in enumerate(zip(media_urls, probes)):
        label = f"Media {i + 1}" if len(media_urls) > 1 else ("Video" if kinds[i] == "video" else "Image")
        if p.get("unreachable"):
            findings.append(_f("warning", "url.public", f"{label}: couldn't download it to check (unreachable, "
                                                        "not public, or over 60 MB). Buffer fetches it when the post goes out."))
            continue
        if p.get("skipped") or p.get("kind") == "unknown":
            continue
        if p["kind"] == "image":
            chips_media.append(f"{p['width']}×{p['height']}")
            findings.extend(_image_rules(svc, net, label, i, p, fixes))
        elif p["kind"] == "video":
            if not p.get("probed"):
                findings.append(_f("info", f"video.{svc}" if f"video.{svc}" in RULE else "url.public",
                                   f"{label}: not inspected ({p.get('why', 'unknown')}). Buffer checks it on publish."))
                continue
            chips_media.append(f"{p.get('width')}×{p.get('height')} · {round(p.get('duration') or 0)} s")
            findings.extend(_video_rules(svc, net, label, p, fixes))

    worst = "error" if any(f["level"] == "error" for f in findings) else "warning" if any(f["level"] == "warning" for f in findings) else "ok"
    chip = f"{net} · {longest:,}/{limit:,}" + (f" · {len(parts)} posts" if len(parts) > 1 else "") + \
           ("".join(f" · {c}" for c in chips_media[:2]))
    return {"channel_id": channel.get("id"), "service": svc, "network": net,
            "channel_name": channel.get("displayName") or channel.get("name") or net,
            "status": worst, "chip": chip, "count": longest, "limit": limit, "parts": len(parts),
            "findings": findings, "fixes": [{"id": k, "label": v} for k, v in fixes.items()],
            "media": [{"url": u, **{k: v for k, v in p.items() if k != "skipped"}} for u, p in zip(media_urls, probes)],
            "rule_pack": RULE_PACK_VERSION}


def _ratio(p: dict) -> float:
    return p["width"] / p["height"] if p.get("height") else 1.0


def _image_rules(svc: str, net: str, label: str, i: int, p: dict, fixes: dict) -> list[dict]:
    out = []
    fx = f"image:{i}"
    size, fmt, r = p["bytes"], p.get("format", ""), _ratio(p)

    def fix(lbl: str):
        fixes[fx] = f"Fit {label.lower()} for {net}" if fx not in fixes else fixes[fx]
        return fx

    if svc == "instagram":
        if fmt != "JPEG":
            out.append(_f("warning", "image.instagram", f"{label} is {fmt or 'not JPEG'}; Instagram's API takes JPEG.", fix("jpeg")))
        if size > 8 * MB:
            out.append(_f("error", "image.instagram", f"{label} is {size / MB:.1f} MB; Instagram allows 8 MB.", fix("shrink")))
        if r < 0.8 - 0.005 or r > 1.91 + 0.005:
            out.append(_f("error", "image.instagram", f"{label} is {p['width']}×{p['height']} ({r:.2f}:1); Instagram feed images "
                                                      "must be between 4:5 and 1.91:1.", fix("crop")))
        if p["width"] > 1440 or p["width"] < 320:
            out.append(_f("info", "image.instagram", f"{label} is {p['width']} px wide; Instagram scales it to 320-1440."))
    elif svc == "threads":
        if fmt not in ("JPEG", "PNG"):
            out.append(_f("warning", "image.threads", f"{label} is {fmt}; Threads officially supports JPEG and PNG.", fix("jpeg")))
        if size > 8 * MB:
            out.append(_f("error", "image.threads", f"{label} is {size / MB:.1f} MB; Threads allows 8 MB.", fix("shrink")))
        if max(r, 1 / r) > 10:
            out.append(_f("error", "image.threads", f"{label} is more than 10:1; Threads won't take it.", fix("crop")))
    elif svc == "twitter":
        cap = 15 * MB if fmt == "GIF" and p.get("animated") else 5 * MB
        if fmt not in ("JPEG", "PNG", "GIF", "WEBP"):
            out.append(_f("error", "image.twitter", f"{label} is {fmt}; X takes JPG, PNG, GIF or WEBP.", fix("jpeg")))
        if size > cap:
            out.append(_f("error", "image.twitter", f"{label} is {size / MB:.1f} MB; X allows {cap // MB} MB.",
                          None if p.get("animated") else fix("shrink")))
    elif svc == "bluesky":
        if size > 1_000_000:
            out.append(_f("warning", "image.bluesky", f"{label} is {size / 1e6:.2f} MB; Bluesky documents 1,000,000 bytes per image.",
                          fix("shrink")))
    elif svc == "linkedin":
        if fmt not in ("JPEG", "PNG", "GIF"):
            out.append(_f("error", "image.linkedin", f"{label} is {fmt}; LinkedIn takes JPG, GIF or PNG.", fix("jpeg")))
        if p["width"] * p["height"] >= 36_152_320:
            out.append(_f("error", "image.linkedin", f"{label} has {p['width'] * p['height']:,} pixels; LinkedIn needs fewer than 36,152,320.",
                          fix("shrink")))
    elif svc == "tiktok":
        if fmt not in ("JPEG", "WEBP"):
            out.append(_f("error", "image.tiktok", f"{label} is {fmt}; TikTok photo posts take JPEG or WebP.", fix("jpeg")))
        if size > 20 * MB:
            out.append(_f("error", "image.tiktok", f"{label} is {size / MB:.1f} MB; TikTok allows 20 MB.", fix("shrink")))
        if min(p["width"], p["height"]) > 1080:
            out.append(_f("warning", "image.tiktok", f"{label} is above 1080p; TikTok's maximum is 1080p.", fix("resize")))
    return out


def _video_rules(svc: str, net: str, label: str, p: dict, fixes: dict) -> list[dict]:
    out = []
    dur, fps, w, h = p.get("duration") or 0, p.get("fps"), p.get("width") or 0, p.get("height") or 0
    kbps, akbps, codec, size = p.get("video_kbps"), p.get("audio_kbps"), (p.get("codec") or "").lower(), p.get("bytes") or 0

    def reencode(rule, msg, level="error"):
        fixes["reencode"] = "Needs re-encoding: run it through Edit media"
        out.append(_f(level, rule, f"{label}: {msg}", "reencode"))

    if svc == "instagram":
        rid = "video.instagram"
        if dur and dur < 3:
            out.append(_f("error", rid, f"{label} is {dur:.1f} s; Instagram Reels must be at least 3 s."))
        if dur > 15 * 60:
            out.append(_f("error", rid, f"{label} is {dur / 60:.1f} min; Instagram Reels can be 15 min."))
        if size > 300 * MB:
            out.append(_f("error", rid, f"{label} is {size / MB:.0f} MB; Instagram allows 300 MB."))
        if codec and codec not in ("h264", "hevc"):
            reencode(rid, f"codec {codec}; Instagram needs H.264 or HEVC.")
        if fps and not 23 <= fps <= 60:
            reencode(rid, f"{fps:g} fps; Instagram needs 23-60 fps.")
        if w > 1920:
            reencode(rid, f"{w} px wide; Instagram allows 1920.")
        if kbps and kbps > 25000:
            reencode(rid, f"{kbps / 1000:.1f} Mbps; Instagram allows 25 Mbps.")
        if akbps and akbps > 128:
            reencode(rid, f"audio is {akbps} kbps; Instagram's spec is 128 kbps.", level="warning")
        if h and abs(w / h - 9 / 16) > 0.02:
            out.append(_f("info", rid, f"{label} is {w}×{h}; Instagram recommends 9:16 for Reels to avoid cropping."))
    elif svc == "threads":
        rid = "video.threads"
        if dur > 300:
            out.append(_f("error", rid, f"{label} is {dur / 60:.1f} min; Threads allows 5 min."))
        if size > 1024 * MB:
            out.append(_f("error", rid, f"{label} is over 1 GB; Threads allows 1 GB."))
        if codec and codec not in ("h264", "hevc"):
            reencode(rid, f"codec {codec}; Threads needs H.264 or HEVC.")
        if fps and not 23 <= fps <= 60:
            reencode(rid, f"{fps:g} fps; Threads needs 23-60 fps.")
        if w > 1920:
            reencode(rid, f"{w} px wide; Threads allows 1920.")
        if kbps and kbps > 100000:
            reencode(rid, f"{kbps / 1000:.0f} Mbps; Threads allows 100 Mbps.")
    elif svc == "twitter":
        rid = "video.twitter"
        if dur and dur < 0.5:
            out.append(_f("error", rid, f"{label} is shorter than 0.5 s."))
        if dur > 20 * 60:
            out.append(_f("warning", rid, f"{label} is {dur / 60:.0f} min; X allows 20 min unless the account has Premium."))
        if fps and fps > 60:
            reencode(rid, f"{fps:g} fps; X allows 60.")
        if h and not (1 / 3 <= w / h <= 3):
            out.append(_f("error", rid, f"{label} is {w}×{h}; X needs an aspect ratio between 1:3 and 3:1."))
    elif svc == "tiktok":
        rid = "video.tiktok"
        if fps and not 23 <= fps <= 60:
            reencode(rid, f"{fps:g} fps; TikTok needs 23-60 fps.")
        if w and h and (min(w, h) < 360 or max(w, h) > 4096):
            reencode(rid, f"{w}×{h}; TikTok needs 360-4096 px on each side.")
        if dur > 600:
            out.append(_f("error", rid, f"{label} is {dur / 60:.1f} min; TikTok takes 10 min at most."))
        elif dur > 180:
            out.append(_f("warning", rid, f"{label} is {dur / 60:.1f} min; many TikTok accounts can only post 3 min."))
        if size > 4096 * MB:
            out.append(_f("error", rid, f"{label} is over 4 GB."))
    elif svc == "youtube":
        if h and w <= h and dur > 180:
            out.append(_f("info", "video.youtube", f"{label} is vertical and {dur / 60:.1f} min, so YouTube treats it as a regular video, not a Short."))
    return out


