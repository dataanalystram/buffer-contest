def markdown_table() -> str:
    rows = ["| Network | Rule | Limit | Source | Checked |", "|---|---|---|---|---|"]
    for r in RULES:
        lim = r["limit"]
        lim_s = "-" if lim is None else (f"{lim / MB:g} MB" if r["kind"] in ("image", "video") and lim >= MB and r["id"] != "image.linkedin"
                                          else f"{lim:,} px" if r["id"] == "image.linkedin" else f"{lim:,}")
        if r["kind"] in ("image", "video") and lim == 1_000_000:
            lim_s = "1,000,000 bytes"
        net = "All" if r["service"] == "*" else NETWORK.get(r["service"], r["service"])
        srcs = " ".join(f"[{urlparse(s.strip()).netloc}]({s.strip()})" for s in r["source"].split(";"))
        rows.append(f"| {net} | {r['what']} | {lim_s} | {srcs} | {CHECKED} |")
    return "\n".join(rows)


